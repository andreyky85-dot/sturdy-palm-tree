import type { GenerateResult } from "@/components/generator/ResultsCards";

// Универсальный учебный генератор: не вызывает OpenAI, а сам собирает тексты под любую тему.
export async function generateContentFromTranscript(transcript: string): Promise<GenerateResult> {
  const short = transcript.slice(0, 140).trim() || "эта тема";
  const topic = short.length > 0 ? short : "эта тема";

  const twitter_posts = [
    `Краткая мысль по теме: "${topic}". Сформулируйте главный вывод в одном предложении — это уже готовый пост.`,
    `Если вам откликается "${topic}", попробуйте объяснить это простыми словами другому человеку. Такой текст лучше всего заходит в соцсетях.`,
    `Люди ценят ясные и честные мысли. Запишите личное наблюдение по теме "${topic}" и оформите его как короткую историю.`,
    `Сделайте серию постов: сегодня — общий взгляд на "${topic}", завтра — один конкретный пример, послезавтра — ошибка, которой стоит избегать.`,
    `Не стремитесь объять всё сразу. Выберите один аспект темы "${topic}" и раскройте только его. Короткий и понятный пост всегда выигрывает.`,
    `Хороший пост отвечает на вопрос: “Зачем мне это знать?”. Сформулируйте для читателя пользу из темы "${topic}".`,
    `Попробуйте оформить свои мысли по теме "${topic}" в формате “3 главных инсайта”, каждый — одним предложением.`,
    `Если вам уже задавали вопросы про "${topic}", превращайте эти вопросы в основу для постов — формат Q&A читается очень легко.`,
    `Добавьте конкретики: вместо общих фраз по теме "${topic}" приведите один реальный пример из жизни или практики.`,
    `В конце поста по теме "${topic}" задайте аудитории простой вопрос — это увеличит вовлечённость и даст новые идеи для контента.`
  ];

  const linkedin_posts = [
    `Тема "${topic}" становится всё более актуальной, но во многих обсуждениях не хватает простоты и структуры.

Полезно смотреть на неё через три призмы:
- контекст: почему это важно именно сейчас,
- практика: как это можно применять на деле,
- выводы: что изменится, если внедрить эти идеи.

Когда вы последовательно отвечаете на эти вопросы, любая сложная тема становится понятной и применимой для аудитории.`,
    `Обсуждая "${topic}", мы часто сталкиваемся с полярными мнениями. Одни считают, что это переоценено, другие — что это “серебряная пуля”.

Правда обычно посередине: ценность появляется тогда, когда есть:
- чёткая цель,
- реалистичные ожидания,
- готовность действовать.

Полезно честно ответить себе: какую роль эта тема должна играть именно в вашей ситуации и какие шаги вы реально готовы сделать.`,
    `Хорошие объяснения сложных тем редко рождаются с первого раза.

Если вы работаете с "${topic}", попробуйте такой подход:
1. Сначала запишите свои мысли в свободной форме.
2. Затем уберите всё лишнее и усложнённые формулировки.
3. Оставьте только то, что даёт читателю ясность и конкретику.

В итоге вы получите текст, который легче читать и легче применять на практике.`,
    `Тема "${topic}" может казаться абстрактной, пока не появляется реальный пример.

Подумайте о ситуации, в которой это уже сыграло роль:
- что было до,
- что вы сделали,
- какой результат получили,
- какие выводы сделали.

Подобные истории гораздо сильнее убеждают, чем любые теоретические рассуждения.`,
    `Когда вы делитесь мыслями по теме "${topic}", вы не обязаны быть “идеальным экспертом”.

Честный формат “вот что я понял на своём опыте, вот что пока не до конца ясно” часто вызывает больше доверия, чем безупречные, но оторванные от реальности тексты.

Главное — искренность, понятная структура и уважение к читателю.`
  ];

  const tiktok_ideas = [
    `Запишите короткое видео “3 вещи, которые стоит знать про ${topic}” — по одному тезису в 3–5 секунд, с крупными субтитрами.`,
    `Сделайте формат “миф vs реальность” по теме ${topic}: сначала популярное заблуждение одним предложением, затем ваше объяснение.`,
    `Снимите ролик “ошибки начинающих в теме ${topic}”: перечислите 2–3 типичные ошибки и кратко покажите, как их избежать.`
  ];

  const blog_summary = `В этом материале разбирается тема "${topic}" и её практическое значение. 
Основной акцент делается на том, как перевести абстрактные идеи в конкретные действия, которые можно применить в реальной жизни или работе.
Разбор строится вокруг контекста, примеров и выводов, чтобы читателю было проще увидеть пользу и придумать свои следующие шаги.`;

  return { twitter_posts, linkedin_posts, tiktok_ideas, blog_summary };
}
